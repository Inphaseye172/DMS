#!/usr/bin/env python3
"""Generates engine/src/colormaps_data.inc: 256-entry RGB lookup tables sampled from matplotlib.

Cyclic maps (twilight, hsv) are excluded: near and far would share a color.
Index 0 of the popup is "None" (grayscale, white = near) and is not stored. Mapped depth value 1.0
(near) samples the end of each map. Append new maps at the END only (popup indices are saved in
projects). Run: python3 -I tools/gen_colormaps.py
"""
import os

import matplotlib

MAPS = [
    ("Turbo", "turbo"), ("Viridis", "viridis"), ("Inferno", "inferno"), ("Magma", "magma"), ("Plasma", "plasma"),
    ("Cividis", "cividis"), ("Jet", "jet"), ("Rainbow", "rainbow"), ("Spectral", "Spectral_r"), ("Coolwarm", "coolwarm"),
    ("RdYlBu", "RdYlBu_r"), ("Cool", "cool"), ("Hot", "hot"), ("Bone", "bone"), ("Copper", "copper"),
    ("Ocean", "ocean"), ("Terrain", "terrain"), ("Earth", "gist_earth"), ("Cubehelix", "cubehelix"), ("Gray Inverted", "gray_r"),
]

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "src", "colormaps_data.inc")


def main():
    lines = ["// Generated by tools/gen_colormaps.py from matplotlib " + matplotlib.__version__ + ". Do not edit.",
             "// Append-only: popup indices are stored in projects.",
             f"constexpr int kColormapCount = {len(MAPS)};",
             "constexpr const char* kColormapNames[kColormapCount] = {" + ", ".join(f'"{n}"' for n, _ in MAPS) + "};",
             "constexpr unsigned char kColormapLut[kColormapCount][256][3] = {"]
    for name, mpl in MAPS:
        cmap = matplotlib.colormaps[mpl]
        rows = []
        for i in range(256):
            r, g, b, _ = cmap(i / 255.0)
            rows.append("{%d,%d,%d}" % (round(r * 255), round(g * 255), round(b * 255)))
        lines.append(f"    {{ // {name}")
        for k in range(0, 256, 16):
            lines.append("        " + ",".join(rows[k:k + 16]) + ",")
        lines.append("    },")
    lines.append("};")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.abspath(OUT))


if __name__ == "__main__":
    main()
